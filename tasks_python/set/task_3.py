'''
На вход программе подается строка текста, содержащая числа. Для каждого числа выведите слово YES (на отдельной строке), если это число ранее встречалось в последовательности, или NO в противном случае.
'''
#code
cach=set()
s=input().split()
for i in s:
    if i.strip('0') not in cach:
        cach.add(i)
        print('NO')
    else: print('YES')



