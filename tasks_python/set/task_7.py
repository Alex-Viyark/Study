'''
На вход программе подаются натуральное число n, а затем n различных натуральных чисел, каждое на отдельной строке. Напишите программу, которая выводит все общие цифры в порядке возрастания у всех введенных чисел.
'''
#code
n=int(input())
s=set(input())
[s.intersection_update(input()) for _ in range(n-1)]
print(*sorted(s))
